/**
 * A bundled Japanese vocabulary and kanji list.
 *
 * Reading Japanese aloud needs to know where words begin and end, because the
 * same kanji is read differently depending on the word it sits in — 人 is
 * "hito" alone but "jin" in 日本人. A full solution needs a morphological
 * analyser and a dictionary of hundreds of thousands of entries; shipping that
 * would mean a multi-megabyte download.
 *
 * So this ships a curated core instead: the words and kanji a learner meets
 * first. Anything outside it is reported as unknown rather than guessed at, so
 * the reader always knows which readings are reliable.
 */

export interface WordEntry {
  /** As written, usually with kanji. */
  word: string;
  /** Reading in hiragana. */
  reading: string;
  meaning: string;
}

export interface KanjiEntry {
  kanji: string;
  /** Readings used in compounds, conventionally written in katakana. */
  on: string[];
  /** Readings used when the kanji stands alone, in hiragana. */
  kun: string[];
  meaning: string;
}

